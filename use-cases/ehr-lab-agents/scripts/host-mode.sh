#!/usr/bin/env bash
# Runs the integration and the lab simulator on the Mac (WSO2 Integrator or `bal run`) while the rest of the
# stack stays in containers. See docker-compose.host.yml for what changes.
#
#   ./scripts/host-mode.sh on        # write the packages' Config.toml, stop their containers, rewire the rest
#   ./scripts/host-mode.sh config    # only rewrite the Config.toml files (after amp-setup.sh or amp-models.sh)
#   ./scripts/host-mode.sh off       # back to everything in containers
#   ./scripts/host-mode.sh status
#
# Then run each package from WSO2 Integrator (open ehr_lab_physician/) or a terminal:
#   cd ehr_lab_physician/ehr_agentic_integration && bal run   # API on :9090
#   cd ehr_lab_physician/lab_simulator && bal run             # API on :9093
#
# The Config.toml files are generated from config/integration.toml, config/lab-simulator.toml and
# secrets.toml with container hostnames swapped for host ports, so model and Agent Manager settings keep one
# source. They are gitignored (the integration's holds the secrets) and kept out of image builds.
set -euo pipefail
cd "$(dirname "$0")/.."

PKG=ehr_lab_physician
INTEGRATION_CONFIG=$PKG/ehr_agentic_integration/Config.toml
LAB_CONFIG=$PKG/lab_simulator/Config.toml
ENV_MARKER="# written by scripts/host-mode.sh"
OVERRIDE=docker-compose.yml:docker-compose.host.yml

log() { printf '\033[1;34m[host-mode]\033[0m %s\n' "$*"; }
die() { printf '\033[1;31m[host-mode]\033[0m %s\n' "$*" >&2; exit 1; }

# Container address → host address. EHR and webhook traffic keeps going through Toxiproxy on its extra ports.
HOST_REWRITES=(
  -e 's#"http://fhir-lab:9090#"http://localhost:8082#g'
  -e 's#^dbHost *= *"postgres"#dbHost = "localhost"#'
  -e 's#^dbPort *= *5432$#dbPort = 5433#'
  -e 's#"http://toxiproxy:8474#"http://localhost:8474#g'
  -e 's#"http://toxiproxy:8081#"http://localhost:18081#g'
  -e 's#"http://toxiproxy:9091#"http://localhost:19091#g'
  -e 's#"http://fhir-mcp-ehr:8000#"http://localhost:8010#g'
  -e 's#"http://fhir-mcp-lab:8000#"http://localhost:8011#g'
  -e 's#"http://pubmed-mcp:8000#"http://localhost:8012#g'
  -e 's#"http://trace-router:4318#"http://localhost:4318#g'
  -e 's#"http://temporal:7243#"http://localhost:7243#g'
  -e 's#^url *= *"temporal:7233"#url = "localhost:7233"#'
  -e 's#"http://llm-auth-adapter:8080#"http://localhost:8015#g'
)
# Any compose service name left in a URL means config gained an address this script does not know yet.
SERVICES='(postgres|fhir-[a-z-]+|toxiproxy|temporal|temporal-ui|pubmed-mcp|trace-router|llm-auth-adapter|judge-adapter|integration|lab-simulator)'
LEFTOVER="\"https?://$SERVICES[:/\"]|^(url|dbHost) *= *\"$SERVICES[:\"]"

write_config() { # <target> <sources…>
  local target=$1; shift
  # WSO2 Integrator adds its ICP runtime settings ([wso2.icp.*]) when remote management is on; keep them.
  local icp=""
  [[ -f $target ]] && icp=$(awk '/^[[:space:]]*\[/{keep = /^[[:space:]]*\[wso2\.icp\./} keep' "$target")
  local tmp; tmp=$(mktemp "$target.XXXXXX")
  chmod 600 "$tmp"
  {
    echo "# Generated by scripts/host-mode.sh from $* — edit those and run \`./scripts/host-mode.sh config\`."
    for src in "$@"; do echo; sed "${HOST_REWRITES[@]}" "$src"; done
    if [[ -n $icp ]]; then printf '\n%s\n' "$icp"; fi
  } >"$tmp"
  if grep -nE "$LEFTOVER" "$tmp" | sed -E 's/=.*/= …/' >&2; then
    rm -f "$tmp"
    die "$target: the lines above still name a container; add a rewrite to HOST_REWRITES in $0"
  fi
  mv "$tmp" "$target"
}

configs() {
  [[ -f secrets.toml ]] || die "secrets.toml is missing (copy secrets.example.toml)"
  write_config "$INTEGRATION_CONFIG" config/integration.toml secrets.toml
  write_config "$LAB_CONFIG" config/lab-simulator.toml
  log "wrote $INTEGRATION_CONFIG and $LAB_CONFIG"
}

listening() { { lsof -nP -iTCP:"$1" -sTCP:LISTEN 2>/dev/null || true; } | awk 'NR==2{print $1}'; }

case "${1:-status}" in
  on)
    if [[ -f .env ]] && ! grep -qF "$ENV_MARKER" .env; then
      die ".env exists and was not written by this script; add COMPOSE_FILE=$OVERRIDE to it yourself"
    fi
    configs
    printf '%s\nCOMPOSE_FILE=%s\n' "$ENV_MARKER" "$OVERRIDE" >.env
    log "stopping the integration and lab simulator containers"
    docker compose stop integration lab-simulator >/dev/null
    log "rewiring portal, Toxiproxy and the LLM auth adapter to the Mac"
    docker compose up -d --no-deps toxiproxy llm-auth-adapter portal >/dev/null
    log "host mode on — now run both packages (WSO2 Integrator, or bal run in each package directory)"
    ;;
  config)
    configs
    ;;
  off)
    for port in 9090 9093; do
      [[ -z "$(listening $port)" || "$(listening $port)" == ssh ]] \
        || die "something on the Mac still listens on :$port ($(listening $port)) — stop the local run first"
    done
    if [[ -f .env ]] && grep -qF "$ENV_MARKER" .env; then rm .env; fi
    log "restoring portal, Toxiproxy and the LLM auth adapter"
    docker compose up -d --no-deps toxiproxy llm-auth-adapter portal >/dev/null
    log "starting the integration and lab simulator containers"
    docker compose up -d --no-deps integration lab-simulator >/dev/null
    log "host mode off — everything runs in containers"
    ;;
  status)
    if [[ -f .env ]] && grep -qF "$ENV_MARKER" .env; then log "host mode: on"; else log "host mode: off"; fi
    for svc in integration:9090 lab-simulator:9093; do
      name=${svc%:*} port=${svc#*:}
      container=$(docker compose ps --status running --services 2>/dev/null | grep -x "$name" || true)
      proc=$(listening "$port")
      if [[ -n $container ]]; then where="container"
      elif [[ -n $proc ]]; then where="Mac ($proc)"
      else where="not running"; fi
      log "  $name :$port — $where"
    done
    ;;
  -h|--help) sed -n '2,17p' "$0" ;;
  *) die "unknown command: $1 (on | config | off | status)" ;;
esac
